#!/usr/bin/env python3
"""Generate gateway/nginx.conf from routes.json (the single routing source of truth).

Usage: python3 gateway/gen_nginx.py [--check]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "runner"))
from routes import load_routes, owner_of  # noqa: E402

PORT = 8000


def render(routes):
    out = []
    w = out.append
    w("# GENERATED by gateway/gen_nginx.py from routes.json. Do not edit by hand.")
    w("worker_processes auto;")
    w("events { worker_connections 1024; }")
    w("http {")
    w("    log_format svc '$remote_addr [$time_local] \"$request\" $status $body_bytes_sent '")
    w("                   'service=$upstream_http_x_fincept_service rt=$request_time';")
    w("    access_log /dev/stdout svc;")
    w("    error_log /dev/stderr warn;")
    w("    # Docker DNS, re-resolved at request time so the gateway starts and keeps")
    w("    # serving when one service is down (that service alone returns 503).")
    w("    resolver 127.0.0.11 valid=5s ipv6=off;")
    w("    client_max_body_size 64m;")
    w("    proxy_read_timeout 3600s;")
    w("    proxy_send_timeout 3600s;")
    w("    proxy_http_version 1.1;")
    w("    default_type application/json;")
    w("    server {")
    w("        listen 80;")
    w("        proxy_intercept_errors on;")
    w("        error_page 502 503 504 = @service_down;")
    w("        location @service_down {")
    w("            add_header X-Fincept-Service-Down $fincept_svc always;")
    w("            return 503 '{\"error\":\"service unavailable\",\"service\":\"$fincept_svc\"}';")
    w("        }")
    w("        location = /healthz { return 200 '{\"ok\":true,\"service\":\"gateway\"}'; }")
    w("        location = /routes.json { alias /etc/nginx/routes.json; }")
    for pat in routes.get("local_only", []):
        w(f"        location ~ ^/v1/scripts/{pat}$ {{")
        w("            add_header X-Fincept-Unrouted 1 always;")
        w("            return 404 '{\"error\":\"script runs in the desktop app\"}';")
        w("        }")
    for svc in routes["services"]:
        name = svc["name"]
        alts = "|".join(f"(?:{p})" for p in svc["scripts"])
        upstream = f"http://{name}:{PORT}"
        w(f"        # {name}: {svc.get('description', '')}")
        w(f"        location ~ ^/v1/scripts/(?:{alts})$ {{")
        w(f"            set $fincept_svc {name};")
        w(f"            set $fincept_up {upstream};")
        w("            proxy_pass $fincept_up;")
        w("        }")
        if owner_of("yfinance_data.py", routes) == name:
            w("        location ~ ^/v1/yfinance/[a-z_]+$ {")
            w(f"            set $fincept_svc {name};")
            w(f"            set $fincept_up {upstream};")
            w("            proxy_pass $fincept_up;")
            w("        }")
        if svc.get("code"):
            w("        location = /v1/code {")
            w(f"            set $fincept_svc {name};")
            w(f"            set $fincept_up {upstream};")
            w("            proxy_pass $fincept_up;")
            w("        }")
        w(f"        location = /services/{name}/healthz {{")
        w(f"            set $fincept_svc {name};")
        w(f"            set $fincept_up {upstream};")
        w("            proxy_pass $fincept_up/healthz;")
        w("        }")
    w("        location /v1/scripts/ {")
    w("            add_header X-Fincept-Unrouted 1 always;")
    w("            return 404 '{\"error\":\"no service owns this script\"}';")
    w("        }")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def main():
    conf = render(load_routes())
    path = os.path.join(HERE, "nginx.conf")
    if "--check" in sys.argv:
        with open(path, encoding="utf-8") as f:
            if f.read() != conf:
                sys.exit("gateway/nginx.conf is stale: run python3 gateway/gen_nginx.py")
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(conf)


if __name__ == "__main__":
    main()
